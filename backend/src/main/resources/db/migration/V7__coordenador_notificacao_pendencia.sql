-- =====================================================
-- CONTROLE DE RESUMO DE PENDENCIAS POR COORDENADOR
-- =====================================================
-- Guarda a ultima quantidade de solicitacoes pendentes que gerou
-- envio de e-mail para o coordenador, por data de referencia.
-- O resumo so e enviado quando a quantidade atual supera a ultima
-- quantidade enviada.

CREATE TABLE coordenador_notificacao_pendencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordenador_id BIGINT NOT NULL,
    data_referencia DATE NOT NULL,
    ultima_quantidade_enviada INTEGER NOT NULL DEFAULT 0,
    enviado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_coord_notif_usuario FOREIGN KEY (coordenador_id)
        REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT uk_coord_notif_data UNIQUE (coordenador_id, data_referencia)
);

CREATE INDEX idx_coord_notif_coordenador
    ON coordenador_notificacao_pendencia(coordenador_id);
