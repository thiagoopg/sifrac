SET DATABASE UNIQUE NAME H2DEV;
SET DATABASE GC 0;

-- Enums
CREATE TYPE USER_PROFILE AS ENUM ('ADMINISTRADOR', 'COORDENADOR', 'ALUNO');
CREATE TYPE REQUEST_STATUS AS ENUM ('PENDENTE', 'DEFERIDO', 'INDEFERIDO', 'CANCELADO');

-- Tabelas
CREATE TABLE CAMPUS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(120) NOT NULL,
    SIGLA VARCHAR(10) NOT NULL UNIQUE,
    CIDADE VARCHAR(80) NOT NULL,
    UF CHAR(2) NOT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE GRAU_CURSO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL UNIQUE,
    DESCRICAO CLOB NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE USUARIO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    LOGIN_LDAP VARCHAR(100) NOT NULL UNIQUE,
    PERFIL USER_PROFILE NOT NULL DEFAULT 'ALUNO',
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CURSO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CAMPUS_ID BIGINT NOT NULL,
    GRAU_ID BIGINT NOT NULL,
    NOME VARCHAR(150) NOT NULL,
    CARGA_HORARIA_AC_EXIGIDA INTEGER NOT NULL DEFAULT 0,
    EMAIL_COORDENACAO VARCHAR(150) NOT NULL UNIQUE,
    COORDENADOR_ID BIGINT NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CURSO_CAMPUS FOREIGN KEY (CAMPUS_ID) REFERENCES CAMPUS(ID),
    CONSTRAINT FK_CURSO_GRAU FOREIGN KEY (GRAU_ID) REFERENCES GRAU_CURSO(ID),
    CONSTRAINT FK_CURSO_COORDENADOR FOREIGN KEY (COORDENADOR_ID) REFERENCES USUARIO(ID)
);

CREATE UNIQUE INDEX UK_CURSO_NOME_CAMPUS ON CURSO(NOME, CAMPUS_ID);

CREATE TABLE TIPO_HORA_COMPLEMENTAR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CURSO_ID BIGINT NOT NULL,
    NOME VARCHAR(150) NOT NULL,
    DESCRICAO CLOB NULL,
    CARGA_HORARIA_MAXIMA INTEGER NULL,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TIPO_CURSO FOREIGN KEY (CURSO_ID) REFERENCES CURSO(ID) ON DELETE CASCADE
);

CREATE UNIQUE INDEX UK_TIPO_CURSO_NOME ON TIPO_HORA_COMPLEMENTAR(CURSO_ID, NOME);

CREATE TABLE ALUNO (
    USUARIO_ID BIGINT PRIMARY KEY,
    CURSO_ID BIGINT NOT NULL,
    MATRICULA VARCHAR(30) NOT NULL UNIQUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ALUNO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE,
    CONSTRAINT FK_ALUNO_CURSO FOREIGN KEY (CURSO_ID) REFERENCES CURSO(ID) ON DELETE RESTRICT
);

CREATE TABLE SOLICITACAO_HORA_COMPLEMENTAR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALUNO_ID BIGINT NOT NULL,
    TIPO_HORA_ID BIGINT NOT NULL,
    HORAS_SOLICITADAS INTEGER NOT NULL DEFAULT 0,
    HORAS_DEFERIDAS INTEGER NULL,
    STATUS REQUEST_STATUS NOT NULL DEFAULT 'PENDENTE',
    JUSTIFICATIVA_COORDENADOR CLOB NULL,
    COORDENADOR_ID BIGINT NULL,
    DATA_SOLICITACAO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_AVALIACAO TIMESTAMP NULL,
    CONSTRAINT FK_SOLIC_ALUNO FOREIGN KEY (ALUNO_ID) REFERENCES ALUNO(USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SOLIC_TIPO FOREIGN KEY (TIPO_HORA_ID) REFERENCES TIPO_HORA_COMPLEMENTAR(ID),
    CONSTRAINT FK_SOLIC_COORDENADOR FOREIGN KEY (COORDENADOR_ID) REFERENCES USUARIO(ID)
);

CREATE TABLE ANEXO_SOLICITACAO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOLICITACAO_ID BIGINT NOT NULL,
    NOME_ARQUIVO VARCHAR(255) NOT NULL,
    URL_ARQUIVO CLOB NOT NULL,
    TAMANHO_BYTES BIGINT NULL,
    ENVIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ANEXO_SOLIC FOREIGN KEY (SOLICITACAO_ID) REFERENCES SOLICITACAO_HORA_COMPLEMENTAR(ID) ON DELETE CASCADE
);

CREATE TABLE NOTIFICACAO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID BIGINT NOT NULL,
    SOLICITACAO_ID BIGINT NULL,
    TITULO VARCHAR(200) NOT NULL,
    MENSAGEM CLOB NOT NULL,
    LIDA BOOLEAN NOT NULL DEFAULT FALSE,
    ENVIADA_POR_EMAIL BOOLEAN NOT NULL DEFAULT FALSE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTIF_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE,
    CONSTRAINT FK_NOTIF_SOLIC FOREIGN KEY (SOLICITACAO_ID) REFERENCES SOLICITACAO_HORA_COMPLEMENTAR(ID)
);

-- Índices
CREATE INDEX IDX_USUARIO_LOGIN_LDAP ON USUARIO(LOGIN_LDAP);
CREATE INDEX IDX_USUARIO_EMAIL ON USUARIO(EMAIL);
CREATE INDEX IDX_USUARIO_PERFIL ON USUARIO(PERFIL);
CREATE INDEX IDX_CURSO_CAMPUS ON CURSO(CAMPUS_ID);
CREATE INDEX IDX_CURSO_GRAU ON CURSO(GRAU_ID);
CREATE INDEX IDX_CURSO_COORDENADOR ON CURSO(COORDENADOR_ID);
CREATE INDEX IDX_TIPO_HORA_CURSO ON TIPO_HORA_COMPLEMENTAR(CURSO_ID);
CREATE INDEX IDX_ALUNO_CURSO ON ALUNO(CURSO_ID);
CREATE INDEX IDX_ALUNO_MATRICULA ON ALUNO(MATRICULA);
CREATE INDEX IDX_SOLIC_ALUNO ON SOLICITACAO_HORA_COMPLEMENTAR(ALUNO_ID);
CREATE INDEX IDX_SOLIC_STATUS ON SOLICITACAO_HORA_COMPLEMENTAR(STATUS);
CREATE INDEX IDX_SOLIC_TIPO ON SOLICITACAO_HORA_COMPLEMENTAR(TIPO_HORA_ID);
CREATE INDEX IDX_ANEXO_SOLIC ON ANEXO_SOLICITACAO(SOLICITACAO_ID);
CREATE INDEX IDX_NOTIF_USUARIO ON NOTIFICACAO(USUARIO_ID);
CREATE INDEX IDX_NOTIF_LIDA ON NOTIFICACAO(USUARIO_ID, LIDA);

