-- Habilitar constraints
SET DATABASE UNIQUE NAME H2DEV;
SET DATABASE GC 0;

-- Enums (H2 usa VARCHAR para enums)
CREATE TYPE USER_ROLE AS ENUM ('ADMIN', 'COORDINATOR', 'STUDENT');
CREATE TYPE ACTIVITY_TYPE AS ENUM ('COURSE', 'EVENT', 'RESEARCH', 'MONITORING', 'PUBLICATION', 'EXTENSION', 'PROFESSIONAL');
CREATE TYPE REQUEST_STATUS AS ENUM ('PENDING', 'UNDER_ANALYSIS', 'APPROVED', 'REJECTED', 'COMPLEMENTATION_REQUESTED');

-- Tabelas
CREATE TABLE CAMPUS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    CODIGO VARCHAR(20) NOT NULL UNIQUE,
    ENDERECO CLOB,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CURSO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    CAMPUS_ID BIGINT NOT NULL,
    CARGA_HORARIA_TOTAL_REQUERIDA INTEGER NOT NULL DEFAULT 0,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CURSO_CAMPUS FOREIGN KEY (CAMPUS_ID) REFERENCES CAMPUS(ID)
);

CREATE UNIQUE INDEX UK_CURSO_NOME_CAMPUS ON CURSO(NOME, CAMPUS_ID);

CREATE TABLE USUARIO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    NOME_COMPLETO VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL,
    CPF VARCHAR(14) NOT NULL UNIQUE,
    SENHA VARCHAR(255),
    ROLE USER_ROLE NOT NULL DEFAULT 'STUDENT',
    CAMPUS_ID BIGINT,
    CURSO_ID BIGINT,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_USUARIO_CAMPUS FOREIGN KEY (CAMPUS_ID) REFERENCES CAMPUS(ID),
    CONSTRAINT FK_USUARIO_CURSO FOREIGN KEY (CURSO_ID) REFERENCES CURSO(ID)
);

CREATE TABLE PREFERENCIA_ATIVIDADE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CURSO_ID BIGINT NOT NULL,
    TIPO_ATIVIDADE ACTIVITY_TYPE NOT NULL,
    HORAS_MAXIMAS INTEGER NOT NULL DEFAULT 0,
    DESCRICAO CLOB,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PREF_CURSO FOREIGN KEY (CURSO_ID) REFERENCES CURSO(ID) ON DELETE CASCADE
);

CREATE UNIQUE INDEX UK_PREF_CURSO_TIPO ON PREFERENCIA_ATIVIDADE(CURSO_ID, TIPO_ATIVIDADE);

CREATE TABLE SOLICITACAO_ATIVIDADE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID BIGINT NOT NULL,
    TIPO_ATIVIDADE ACTIVITY_TYPE NOT NULL,
    STATUS REQUEST_STATUS NOT NULL DEFAULT 'PENDING',
    HORAS_SOLICITADAS INTEGER NOT NULL DEFAULT 0,
    HORAS_APROVADAS INTEGER DEFAULT 0,
    JUSTIFICATIVA CLOB NOT NULL,
    COORDENADOR_NOTAS CLOB,
    ANALISADO_POR BIGINT,
    ANALISADO_EM TIMESTAMP,
    SOLICITACAO_ANTERIOR_ID BIGINT,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SOLIC_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE,
    CONSTRAINT FK_SOLIC_ANALISADOR FOREIGN KEY (ANALISADO_POR) REFERENCES USUARIO(ID),
    CONSTRAINT FK_SOLIC_ANTERIOR FOREIGN KEY (SOLICITACAO_ANTERIOR_ID) REFERENCES SOLICITACAO_ATIVIDADE(ID)
);

CREATE TABLE AUDIT_SOLICITACAO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOLICITACAO_ID BIGINT NOT NULL,
    OLD_STATUS REQUEST_STATUS,
    NEW_STATUS REQUEST_STATUS,
    OLD_HORAS INTEGER,
    NEW_HORAS INTEGER,
    ALTERADO_POR BIGINT NOT NULL,
    OBSERVACAO CLOB,
    ENVIADO_EMAIL BOOLEAN NOT NULL DEFAULT FALSE,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_AUDIT_SOLIC FOREIGN KEY (SOLICITACAO_ID) REFERENCES SOLICITACAO_ATIVIDADE(ID) ON DELETE CASCADE,
    CONSTRAINT FK_AUDIT_USUARIO FOREIGN KEY (ALTERADO_POR) REFERENCES USUARIO(ID)
);

CREATE TABLE DOCUMENTO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOLICITACAO_ID BIGINT NOT NULL,
    NOME_ARQUIVO VARCHAR(255) NOT NULL,
    NOME_ORIGINAL VARCHAR(255) NOT NULL,
    CAMINHO_SERVIDOR VARCHAR(500) NOT NULL,
    TAMANHO_BYTES BIGINT NOT NULL DEFAULT 0,
    TIPO_MIME VARCHAR(100),
    UPLOADADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPLOADADO_POR BIGINT NOT NULL,
    CONSTRAINT FK_DOC_SOLIC FOREIGN KEY (SOLICITACAO_ID) REFERENCES SOLICITACAO_ATIVIDADE(ID) ON DELETE CASCADE,
    CONSTRAINT FK_DOC_USUARIO FOREIGN KEY (UPLOADADO_POR) REFERENCES USUARIO(ID)
);

CREATE TABLE NOTIFICACAO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID BIGINT NOT NULL,
    TITULO VARCHAR(200) NOT NULL,
    MENSAGEM CLOB NOT NULL,
    LIDO BOOLEAN NOT NULL DEFAULT FALSE,
    TIPO VARCHAR(50) NOT NULL DEFAULT 'INFO',
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTIF_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO(ID) ON DELETE CASCADE
);

-- Índices
CREATE INDEX IDX_USUARIO_USERNAME ON USUARIO(USERNAME);
CREATE INDEX IDX_USUARIO_EMAIL ON USUARIO(EMAIL);
CREATE INDEX IDX_USUARIO_CPF ON USUARIO(CPF);
CREATE INDEX IDX_USUARIO_ROLE ON USUARIO(ROLE);
CREATE INDEX IDX_USUARIO_CAMPUS ON USUARIO(CAMPUS_ID);
CREATE INDEX IDX_USUARIO_CURSO ON USUARIO(CURSO_ID);
CREATE INDEX IDX_SOLIC_USUARIO ON SOLICITACAO_ATIVIDADE(USUARIO_ID);
CREATE INDEX IDX_SOLIC_STATUS ON SOLICITACAO_ATIVIDADE(STATUS);
CREATE INDEX IDX_SOLIC_TIPO ON SOLICITACAO_ATIVIDADE(TIPO_ATIVIDADE);
CREATE INDEX IDX_AUDIT_SOLIC ON AUDIT_SOLICITACAO(SOLICITACAO_ID);
CREATE INDEX IDX_DOC_SOLIC ON DOCUMENTO(SOLICITACAO_ID);
CREATE INDEX IDX_NOTIF_USUARIO ON NOTIFICACAO(USUARIO_ID);
CREATE INDEX IDX_NOTIF_LIDO ON NOTIFICACAO(USUARIO_ID, LIDO);

